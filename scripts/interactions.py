"""Tests d'interaction de bout en bout (desktop + mobile + mouvement réduit)."""
import asyncio, sys
from playwright.async_api import async_playwright, expect

BASE = sys.argv[1]; OUT = sys.argv[2]
ok = lambda m: print("  ✓", m)

async def desktop(b):
    print("DESKTOP")
    pg = await b.new_page(viewport={"width": 1440, "height": 900})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.goto(BASE + "/produits/peche-blanche-fleur-oranger", wait_until="networkidle")
    await pg.get_by_text("Bouteille professionnelle 700 ml").click()
    await expect(pg.get_by_text("14,90 € ").first).to_be_visible(); ok("sélection du format pro (prix HT)")
    await pg.get_by_role("button", name="Ajouter un").first.click()
    await pg.get_by_role("button", name="Ajouter au panier").first.click()
    await expect(pg.get_by_role("status").filter(has_text="Ajouté au panier")).to_be_visible(); ok("confirmation d'ajout")
    await expect(pg.get_by_role("button", name="Panier, 2 articles")).to_be_visible(); ok("compteur du panier = 2")
    await pg.screenshot(path=f"{OUT}/i_added.png")
    await pg.get_by_role("button", name="Voir le panier").click()
    drawer = pg.get_by_role("dialog", name="Panier")
    await expect(drawer).to_be_visible(); ok("ouverture du tiroir panier")
    await expect(drawer.get_by_text("29,80 € HT")).to_be_visible(); ok("total HT calculé (2 × 14,90)")
    await pg.screenshot(path=f"{OUT}/i_drawer.png")
    await pg.keyboard.press("Escape"); await expect(drawer).to_be_hidden(); ok("fermeture au clavier (Échap)")
    # ajout d'un produit particulier depuis la boutique
    await pg.goto(BASE + "/boutique?categorie=poudre", wait_until="networkidle")
    cards = pg.locator("article")
    await expect(cards).to_have_count(4); ok("filtre catégorie depuis l'URL (4 poudres)")
    await pg.get_by_role("button", name="Filtres (1)").click()
    await pg.get_by_role("button", name="Hiver").click()
    await expect(cards).to_have_count(1); ok("filtre saison combiné (1 résultat)")
    await cards.first.get_by_role("button", name="Ajouter", exact=True).click()
    await pg.wait_for_timeout(400)
    await pg.get_by_role("button", name="Effacer les filtres").click()
    await expect(cards).to_have_count(10); ok("réinitialisation des filtres (10 créations)")
    await pg.get_by_placeholder("Rechercher une saveur…").fill("fleur d'oranger")
    await expect(cards).to_have_count(2); ok("recherche « fleur d'oranger » (2 résultats)")
    await pg.get_by_placeholder("Rechercher une saveur…").fill("")
    # favoris
    await pg.get_by_role("button", name="Ajouter Poire fondante & Vanille Bourbon aux favoris").click()
    await pg.goto(BASE + "/favoris", wait_until="networkidle")
    await expect(pg.get_by_text("Poire fondante & Vanille Bourbon").first).to_be_visible(); ok("favori persistant après navigation")
    # persistance + page panier
    await pg.goto(BASE + "/panier", wait_until="networkidle")
    await expect(pg.get_by_text("Sous-total particuliers")).to_be_visible()
    await expect(pg.get_by_text("Sous-total formats professionnels")).to_be_visible(); ok("panier persistant, sous-totaux TTC et HT séparés")
    await pg.reload(wait_until="networkidle")
    await expect(pg.get_by_text("Chocolat intense & Biscuit doré").first).to_be_visible(); ok("panier conservé après rechargement")
    # commande simulée
    await pg.get_by_role("link", name="Simuler la commande").click()
    await pg.wait_for_url("**/commande")
    await pg.get_by_role("button", name="Continuer vers la livraison").click()
    await expect(pg.get_by_text("Indiquez une adresse e-mail complète.")).to_be_visible(); ok("validation des champs de commande")
    await pg.get_by_label("Prénom").fill("Camille"); await pg.get_by_label("Nom", exact=True).fill("Test")
    await pg.get_by_label("E-mail").fill("camille@exemple.fr"); await pg.get_by_label("Ville").fill("Lyon")
    await pg.get_by_role("button", name="Continuer vers la livraison").click()
    await pg.get_by_role("button", name="Vérifier la commande").click()
    await pg.get_by_role("button", name="Terminer la simulation").click()
    await expect(pg.get_by_text("Simulation terminée.")).to_be_visible(); ok("fin de simulation, référence DEMO")
    await expect(pg.get_by_role("button", name="Panier, 0 article")).to_be_visible(); ok("panier vidé après simulation")
    await pg.screenshot(path=f"{OUT}/i_done.png")
    # recherche globale
    await pg.get_by_role("button", name="Rechercher").first.click()
    await pg.get_by_label("Rechercher une saveur, une recette, un article").fill("chocolat")
    await expect(pg.get_by_role("dialog", name="Recherche").get_by_text("Chocolat intense & Biscuit doré")).to_be_visible(); ok("recherche globale (produits, recettes)")
    await pg.keyboard.press("Escape")
    # saisons au clavier
    await pg.goto(BASE + "/", wait_until="networkidle")
    tab = pg.get_by_role("tab", name="III Automne")
    await tab.scroll_into_view_if_needed(); await tab.focus(); await pg.keyboard.press("ArrowRight")
    await expect(pg.get_by_role("tab", name="IV Hiver")).to_have_attribute("aria-selected", "true"); ok("onglets saisons au clavier")
    await pg.wait_for_timeout(1300)
    await pg.get_by_role("tabpanel").screenshot(path=f"{OUT}/i_hiver.png")
    # formulaire pro
    await pg.goto(BASE + "/professionnels#demande", wait_until="networkidle")
    await pg.get_by_role("button", name="Envoyer la demande (démonstration)").click()
    await expect(pg.get_by_text("Indiquez le nom de l'établissement.")).to_be_visible(); ok("validation du formulaire professionnel")
    await pg.get_by_label("Établissement", exact=True).fill("Café du Port"); await pg.get_by_label("Type d'établissement").select_option("Coffee shop")
    await pg.get_by_label("Nom et prénom").fill("Alex Martin"); await pg.get_by_label("E-mail professionnel").fill("alex@cafe.fr")
    await pg.get_by_label("Ville", exact=True).fill("Nantes"); await pg.get_by_text("Échantillons", exact=True).click()
    await pg.get_by_label("Votre projet").fill("Nous cherchons des sirops de saison pour notre carte d'automne.")
    await pg.get_by_label("J'ai compris").check()
    await pg.get_by_role("button", name="Envoyer la demande (démonstration)").click()
    await expect(pg.get_by_text("Demande validée — mode démonstration.")).to_be_visible(); ok("envoi simulé du formulaire pro")
    print("  erreurs JS :", errs or "aucune")
    await pg.close()

async def mobile(b):
    print("MOBILE")
    ctx = await b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, device_scale_factor=2)
    pg = await ctx.new_page()
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.goto(BASE + "/", wait_until="networkidle"); await pg.wait_for_timeout(1800)
    await pg.screenshot(path=f"{OUT}/m_hero.png")
    await pg.get_by_role("button", name="Ouvrir le menu").click()
    menu = pg.get_by_role("dialog", name="Menu")
    await expect(menu).to_be_visible(); await pg.wait_for_timeout(900)
    await pg.screenshot(path=f"{OUT}/m_menu.png"); ok("menu plein écran")
    await menu.get_by_role("link", name="Recettes").click()
    await pg.wait_for_url("**/recettes"); await expect(menu).to_be_hidden(); ok("navigation depuis le menu, fermeture automatique")
    await pg.goto(BASE + "/produits/datte-medjool-creme-brulee", wait_until="networkidle")
    await pg.wait_for_timeout(800)
    for y in (600, 1200, 1800):
        await pg.evaluate(f"window.scrollTo(0, {y})"); await pg.wait_for_timeout(500)
    bar = pg.locator("div.fixed.bottom-0")
    await expect(bar).to_be_visible(); ok("barre d'achat collante sur fiche produit")
    await pg.screenshot(path=f"{OUT}/m_bar.png")
    await bar.get_by_role("button", name="Ajouter").click()
    await expect(pg.get_by_role("button", name="Panier, 1 article")).to_be_visible(); ok("ajout depuis la barre mobile")
    print("  erreurs JS :", errs or "aucune")
    await ctx.close()

async def reduced(b):
    print("MOUVEMENT RÉDUIT")
    ctx = await b.new_context(viewport={"width": 1280, "height": 800}, reduced_motion="reduce")
    pg = await ctx.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    await pg.goto(BASE + "/", wait_until="networkidle"); await pg.wait_for_timeout(300)
    vis = await pg.evaluate("getComputedStyle(document.querySelector('#hero-titre span span')).transform")
    print("  transform du titre :", vis); ok("titre visible immédiatement" if vis in ("none", "matrix(1, 0, 0, 1, 0, 0)") else "TITRE ENCORE MASQUÉ")
    await pg.screenshot(path=f"{OUT}/r_home.png")
    print("  erreurs JS :", errs or "aucune")
    await ctx.close()

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/opt/pw-browsers/chromium-1194/chrome-linux/chrome")
        for f in (desktop, mobile, reduced):
            try: await f(b)
            except Exception as e: print("  ✗ ÉCHEC", f.__name__, str(e)[:600])
        await b.close()
asyncio.run(main())
